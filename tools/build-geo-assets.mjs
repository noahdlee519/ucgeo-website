// Generates the static geo assets used by the site. Run from this folder:
//
//   npm install && node build-geo-assets.mjs
//
// Outputs (committed, so the site itself has no build step):
//   ../world-map-data.js     Equal Earth world map (Natural Earth 1:110m, public domain)
//   ../icons/topo-light.svg  Topographic contour texture, white lines (for dark backgrounds)
//   ../icons/topo-dark.svg   Topographic contour texture, blue lines (for light backgrounds)

import { readFileSync, writeFileSync } from 'node:fs';
import { geoEqualEarth, geoPath, geoGraticule10, geoArea } from 'd3-geo';
import { contours } from 'd3-contour';
import { line, curveBasisClosed } from 'd3-shape';
import { feature } from 'topojson-client';
import countriesIso from 'i18n-iso-countries';

const world = JSON.parse(readFileSync(new URL('./node_modules/world-atlas/countries-110m.json', import.meta.url)));
const out = (p) => new URL(p, import.meta.url);

// ---------- World map ----------
const WIDTH = 1000;
const CHICAGO = [-87.6298, 41.8781];

const projection = geoEqualEarth().fitWidth(WIDTH, { type: 'Sphere' });
const path = geoPath(projection).digits(1);
const coarsePath = geoPath(projection).digits(0);
const height = Math.round(projection([0, -58])[1]); // crop below the Southern Ocean

const countries = {};
for (const f of feature(world, world.objects.countries).features) {
  if (f.id === '010') continue; // Antarctica
  const key = (f.id && countriesIso.numericToAlpha2(f.id)) || f.properties.name;

  // Anchor routes on the largest polygon so outlying islands don't drag the point offshore.
  let anchor = f;
  if (f.geometry.type === 'MultiPolygon') {
    const polys = f.geometry.coordinates.map((c) => ({ type: 'Polygon', coordinates: c }));
    anchor = polys.reduce((a, b) => (geoArea(b) > geoArea(a) ? b : a));
  }
  const [cx, cy] = path.centroid(anchor);
  countries[key] = { n: f.properties.name, d: coarsePath(f), c: [+cx.toFixed(1), +cy.toFixed(1)] };
}

const chicago = projection(CHICAGO).map((v) => +v.toFixed(1));
const data = {
  w: WIDTH,
  h: height,
  sphere: path({ type: 'Sphere' }),
  graticule: coarsePath(geoGraticule10()),
  chicago,
  countries,
};
writeFileSync(
  out('../world-map-data.js'),
  '// Generated by tools/build-geo-assets.mjs. Natural Earth 1:110m (public domain), Equal Earth projection.\n' +
    'window.UCGEO_WORLD = ' + JSON.stringify(data) + ';\n'
);

// ---------- Topographic contour textures ----------
// Seeded fractal value noise, so the texture is identical on every rebuild.
function mulberry32(a) {
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(1890); // UChicago founding year
const LATTICE = 64;
const lattice = Array.from({ length: LATTICE * LATTICE }, rand);
const smooth = (t) => t * t * (3 - 2 * t);
function valueNoise(x, y) {
  const xi = Math.floor(x), yi = Math.floor(y);
  const xf = smooth(x - xi), yf = smooth(y - yi);
  const v = (i, j) => lattice[((j & (LATTICE - 1)) * LATTICE) + (i & (LATTICE - 1))];
  const a = v(xi, yi), b = v(xi + 1, yi), c = v(xi, yi + 1), d = v(xi + 1, yi + 1);
  return a + (b - a) * xf + (c - a) * yf + (a - b - c + d) * xf * yf;
}
function fbm(x, y) {
  let sum = 0, amp = 1, freq = 1, norm = 0;
  for (let o = 0; o < 4; o++) {
    sum += amp * valueNoise(x * freq, y * freq);
    norm += amp; amp *= 0.5; freq *= 2;
  }
  return sum / norm;
}

const GW = 120, GH = 75, SVG_W = 800, SVG_H = 500;
const values = new Float64Array(GW * GH);
for (let j = 0; j < GH; j++) {
  for (let i = 0; i < GW; i++) {
    values[j * GW + i] = fbm(i / 19, j / 19);
  }
}
const min = Math.min(...values), max = Math.max(...values);
const LEVELS = 18;
const thresholds = Array.from({ length: LEVELS }, (_, k) => min + ((k + 0.5) * (max - min)) / LEVELS);
const sx = SVG_W / (GW - 1), sy = SVG_H / (GH - 1);
const ringPath = line().curve(curveBasisClosed).x((p) => p[0] * sx).y((p) => p[1] * sy).digits(0);

function topoSvg(stroke, minorOpacity, majorOpacity) {
  const minor = [], major = [];
  contours().size([GW, GH]).thresholds(thresholds)(values).forEach((mp, k) => {
    const d = mp.coordinates
      .flat()
      .filter((ring) => ring.length > 6) // drop tiny specks
      .map((ring) => ringPath(ring.slice(0, -1)))
      .join('');
    (k % 5 === 0 ? major : minor).push(d); // every fifth line is an index contour
  });
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SVG_W} ${SVG_H}" preserveAspectRatio="xMidYMid slice">` +
    `<g fill="none" stroke="${stroke}" stroke-linejoin="round">` +
    `<path stroke-opacity="${minorOpacity}" stroke-width="1" vector-effect="non-scaling-stroke" d="${minor.join('')}"/>` +
    `<path stroke-opacity="${majorOpacity}" stroke-width="1.8" vector-effect="non-scaling-stroke" d="${major.join('')}"/>` +
    `</g></svg>\n`
  );
}
writeFileSync(out('../icons/topo-light.svg'), topoSvg('#ffffff', 0.2, 0.36));
writeFileSync(out('../icons/topo-dark.svg'), topoSvg('#26a8ff', 0.2, 0.36));

console.log(`world-map-data.js: ${Object.keys(countries).length} countries, ${WIDTH}x${height}`);
